#!/usr/bin/env node
// Creates .env.local for local development with fresh random secrets, if it doesn't exist yet. Never overwrites,
// and prints no values. It writes only the keys it generates: an empty key in .env.local would override a value
// you keep in .env (Next.js gives .env.local priority), so put Azure OpenAI, Bedrock and SMTP values in either
// file yourself. .env.example lists every variable.
import { randomBytes } from 'node:crypto';
import { existsSync, writeFileSync } from 'node:fs';

const target = '.env.local';
if (existsSync(target)) {
  console.log(`${target} already exists; left unchanged.`);
  process.exit(0);
}
const hex = n => randomBytes(n).toString('hex');
const pw = { POSTGRES_PASSWORD: hex(24), DEMANDAI_OWNER_PASSWORD: hex(24), DEMANDAI_APP_PASSWORD: hex(24), DEMANDAI_OPS_PASSWORD: hex(24) };
const values = {
  NODE_ENV: 'development',
  APP_BASE_URL: 'http://localhost:3000',
  POSTGRES_USER: 'postgres',
  POSTGRES_DB: 'demandai',
  ...pw,
  DATABASE_URL: `postgresql://demandai_app:${pw.DEMANDAI_APP_PASSWORD}@127.0.0.1:55432/demandai`,
  DATABASE_MIGRATION_URL: `postgresql://demandai_owner:${pw.DEMANDAI_OWNER_PASSWORD}@127.0.0.1:55432/demandai`,
  DATABASE_OPS_URL: `postgresql://demandai_ops:${pw.DEMANDAI_OPS_PASSWORD}@127.0.0.1:55432/demandai`,
  DATABASE_SSL_MODE: 'disable',
  SESSION_SECRET: randomBytes(48).toString('base64url'),
  NOTIFICATION_DISABLED: '1',
  // Password for the fictional seeded users (npm run db:seed); local development only.
  DEV_SEED_PASSWORD: `dev-${randomBytes(12).toString('base64url')}`,
};
const body = Object.entries(values).map(([k, v]) => `${k}=${v}`).join('\n');
writeFileSync(target, `# Local development only. Generated by scripts/dev/init-env.mjs; never commit. See .env.example for every variable.\n${body}\n`, { mode: 0o600 });
console.log(`${target} created with random development secrets (${Object.keys(values).length} variables).`);
